<?php

declare(strict_types=1);

/**
 * @param array<string, int> $nouns
 * @param array<string, int> $others
 * @param array<string, string> $verbs
 * @return int the bytes written
 */
function writeLexiconFiles(string $directory, array $nouns, array $others, array $verbs): int
{
    $files = [
        'lexicon.tsv' => lexiconLines($nouns, $others),
        'verbs.tsv' => verbLines($verbs),
        'lexicon-meta.php' => metaSource($nouns, $others),
    ];
    $bytes = 0;
    foreach ($files as $name => $content) {
        file_put_contents($directory . '/' . $name, $content);
        $bytes += strlen($content);
    }

    return $bytes;
}

/**
 * @param array<string, int> $nouns
 * @param array<string, int> $others
 */
function lexiconLines(array $nouns, array $others): string
{
    $entries = [];
    foreach ($nouns as $form => $class) {
        $entries[(string) $form] = 'n' . "\t" . $class;
    }
    foreach ($others as $form => $class) {
        $entries[(string) $form] = 'o' . "\t" . $class;
    }

    return sortedLines($entries);
}

/** @param array<string, string> $verbs */
function verbLines(array $verbs): string
{
    return sortedLines($verbs);
}

/** @param array<string, string> $entries */
function sortedLines(array $entries): string
{
    ksort($entries, SORT_STRING);
    $lines = '';
    foreach ($entries as $key => $value) {
        $lines .= $key . "\t" . $value . "\n";
    }

    return $lines;
}

/**
 * @param array<string, int> $nouns
 * @param array<string, int> $others
 */
function metaSource(array $nouns, array $others): string
{
    $classesByLength = [];
    foreach ($nouns as $noun => $class) {
        $classesByLength[mb_strlen((string) $noun)][] = $class;
    }
    ksort($classesByLength);
    $medians = [];
    foreach ($classesByLength as $length => $classes) {
        sort($classes);
        $medians[$length] = $classes[intdiv(count($classes), 2)];
    }

    $rows = '';
    foreach ($medians as $length => $class) {
        $rows .= sprintf("        %d => %d,\n", $length, $class);
    }

    return "<?php\n\n// Generated by resources/german-lexicon/generate.php; see SOURCE and NOTICE.txt. Do not edit.\n\n"
        . "declare(strict_types=1);\n\nreturn [\n    'rarest' => " . max($nouns + $others) . ",\n"
        . "    'medianNounClassByLength' => [\n" . $rows . "    ],\n];\n";
}
